/**
 * Prepare a prebuilt `android/` for a signed release build **off** EAS Build.
 *
 * ## Why this stopped being obsolete — 2026-08-17
 *
 * This script was marked OBSOLETE on 2026-08-07 for one specific reason: it
 * could not inject the EAS Update **channel** into `AndroidManifest.xml`.
 * `expo prebuild` never reads `eas.json`, so a raw-Gradle build omitted the
 * channel and the binary silently could not receive OTA updates — it compiled,
 * signed, and shipped, then called `u.expo.dev` with no `expo-channel-name`
 * header. That shipped as vc 10, which is why vc 11 exists.
 *
 * Step 4 below closes exactly that gap, so the reason for the obsolescence is
 * gone. Expo documents this as a first-class path ("Using EAS Update without
 * EAS Build"): the channel is a request header, and the Android manifest key
 * that carries it is
 * `expo.modules.updates.UPDATES_CONFIGURATION_REQUEST_HEADERS_KEY` — read out
 * of `expo-updates`' own `UpdatesConfiguration.kt:253`, not out of a doc.
 *
 * **`eas build --local` on a Mac is still the preferred path** when a Mac is
 * available: it does all of this without a hand-rolled patch. This exists
 * because `eas build --local` refuses to run Android off Linux/macOS
 * (`eas-cli`'s `checkRuntime.ts`), so a Windows workstation cannot use it at
 * all. Verify the result rather than trusting it — the failure mode here is
 * silent by construction:
 *
 *     unzip -p app-release.aab base/manifest/AndroidManifest.xml \
 *       | grep -a -c expo-channel-name        # must be >= 1
 *
 * **The channel is deliberately NOT put in `app.json`.** `updates.requestHeaders`
 * would work and is the documented CNG option, but `app.json` is hashed *whole*
 * for the fingerprint runtime policy, so adding a key there moves BOTH
 * platforms' runtime versions — including iOS, whose build 55 is the pending
 * App Store binary. Patching the gitignored `android/` keeps the blast radius
 * on the platform and machine actually doing the build.
 *
 * ## The release ABI set lives here too, and for the same reason — 2026-08-19
 *
 * Step 1b writes `reactNativeArchitectures`. It was first written in
 * `plugins/withGradleJvmArgs.js` (`1ddb51fa`), and that cost a channel: a config
 * plugin's file contents are a hashed fingerprint source (`expoConfigPlugins`),
 * so an **Android-only** build-speed tweak moved the **iOS** runtime too, from
 * `7b347b0f…` to `6670f678…`. iOS build 60 was in App Store review on
 * `7b347b0f…`, so 1.2.1 was heading for release with no over-the-air fix path.
 * Measured on both hosts 2026-08-19: restoring that file byte-for-byte returns
 * iOS to `7b347b0f…` and Android to `ae526937…`.
 *
 * The paragraph above already had the right rule — put Android-only build
 * config in the gitignored `android/`, not in anything hashed. The ABI set is
 * exactly that: it changes which `.so`s Gradle compiles on this workstation and
 * nothing about the JS or the iOS project. Here it is also *automatic*, which a
 * `-P` flag on the Gradle invocation is not — a forgotten flag silently ships
 * four ABIs and costs ~6 minutes, and a flag written into `eas.json` would
 * re-shut both channels, because `eas.json` is itself a hashed source
 * (reason: `easBuild`).
 *
 * ---
 *
 * Prepare the prebuilt `android/` project for a signed local release build.
 *
 * `android/` is gitignored and regenerated by `expo prebuild`, so this runs
 * AFTER every prebuild. Two things Expo's template does not do for us:
 *
 * 1. **Release signing.** The generated `build.gradle` points the `release`
 *    buildType at `signingConfigs.debug` — a debug-keystore-signed AAB, which
 *    Play rejects as the wrong upload cert. We inject a real `release` signing
 *    config fed from `credentials.json` (the same keystore EAS uses via
 *    `credentialsSource: "local"`), passing secrets through `gradle.properties`
 *    so they never land in a tracked file or a build script.
 *
 * 2. **versionCode.** `eas.json` sets `appVersionSource: "remote"`, so the
 *    counter lives on EAS and the generated `build.gradle` always says `1`.
 *    A local build must be told the number explicitly, and whoever runs it must
 *    then push the same number back to EAS (`eas build:version:set`) or the next
 *    cloud build will re-mint it and collide at Play.
 *
 * Usage: node scripts/patch-android-release.mjs <versionCode> [channel]
 *   channel defaults to "production" — it must match a channel that exists on
 *   EAS (`eas channel:list`), or the build calls a channel nothing publishes to.
 */
import { readFileSync, writeFileSync, existsSync, appendFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const mobileRoot = resolve(here, '..');

const versionCode = process.argv[2];
if (!/^\d+$/.test(versionCode ?? '')) {
  console.error('usage: node scripts/patch-android-release.mjs <versionCode> [channel]');
  process.exit(1);
}
const channel = process.argv[3] ?? 'production';

const credsPath = resolve(mobileRoot, 'credentials.json');
if (!existsSync(credsPath)) {
  console.error('credentials.json missing — cannot sign. See CLAUDE.local.md.');
  process.exit(1);
}
const { keystorePath, keystorePassword, keyAlias, keyPassword } =
  JSON.parse(readFileSync(credsPath, 'utf8')).android.keystore;

const storeFile = resolve(mobileRoot, keystorePath);
if (!existsSync(storeFile)) {
  console.error(`keystore not found at ${storeFile}`);
  process.exit(1);
}

// --- 1. secrets into android/gradle.properties (inside gitignored android/) ---
const gradleProps = resolve(mobileRoot, 'android/gradle.properties');
let props = readFileSync(gradleProps, 'utf8');
if (!props.includes('IGNIA_STORE_FILE')) {
  appendFileSync(
    gradleProps,
    [
      '',
      '# Injected by scripts/patch-android-release.mjs — release signing.',
      '# android/ is gitignored, so these do not reach the repo.',
      `IGNIA_STORE_FILE=${storeFile.replace(/\\/g, '/')}`,
      `IGNIA_STORE_PASSWORD=${keystorePassword}`,
      `IGNIA_KEY_ALIAS=${keyAlias}`,
      `IGNIA_KEY_PASSWORD=${keyPassword}`,
      '',
    ].join('\n'),
  );
  console.log('gradle.properties: signing properties appended');
} else {
  console.log('gradle.properties: signing properties already present');
}

// --- 1b. release ABI set (see "The release ABI set lives here too" above) ---
// Every native compile on the Windows workstation runs EMULATED: the NDK ships a
// `windows-x86_64` toolchain only — there is no `windows-aarch64` — and this box
// is a Snapdragon X, so each ABI is a full emulated C++ build. The Expo template
// defaults to four. `x86`/`x86_64` are run by emulators and a few x86
// Chromebooks; no phone uses them, there is no emulator host on this project at
// all, and Play serves per-device splits from the AAB so they never cost a user a
// byte — only the build host. Measured 2026-08-19: 16m 04s (4 ABIs) -> 10m 29s
// (2 ABIs), AAB 101 MB -> 66 MB. `armeabi-v7a` stays because minSdkVersion is 26.
// Override for a LOCAL check only with -PreactNativeArchitectures=arm64-v8a; a
// -P flag beats gradle.properties, and one ABI is ~75% off the native time.
const ABIS = 'armeabi-v7a,arm64-v8a';
props = readFileSync(gradleProps, 'utf8');
if (new RegExp(`^reactNativeArchitectures=${ABIS}$`, 'm').test(props)) {
  console.log(`gradle.properties: reactNativeArchitectures already ${ABIS}`);
} else if (/^reactNativeArchitectures=.*$/m.test(props)) {
  const before = props.match(/^reactNativeArchitectures=(.*)$/m)[1];
  props = props.replace(/^reactNativeArchitectures=.*$/m, `reactNativeArchitectures=${ABIS}`);
  writeFileSync(gradleProps, props);
  console.log(`gradle.properties: reactNativeArchitectures ${before} -> ${ABIS}`);
} else {
  // The template has always shipped this key. If it is gone, the template moved
  // under us — fail loudly rather than silently build four ABIs and blame Gradle.
  console.error('reactNativeArchitectures absent from android/gradle.properties — template changed. Aborting.');
  process.exit(1);
}

// --- 2. build.gradle: real release signingConfig + versionCode ---
const buildGradlePath = resolve(mobileRoot, 'android/app/build.gradle');
let gradle = readFileSync(buildGradlePath, 'utf8');

if (!gradle.includes('IGNIA_STORE_FILE')) {
  // Add a `release` entry alongside the template's `debug` one.
  gradle = gradle.replace(
    /(signingConfigs \{\n)/,
    `$1        release {
            if (project.hasProperty('IGNIA_STORE_FILE')) {
                storeFile file(IGNIA_STORE_FILE)
                storePassword IGNIA_STORE_PASSWORD
                keyAlias IGNIA_KEY_ALIAS
                keyPassword IGNIA_KEY_PASSWORD
            }
        }\n`,
  );
  // Point the release buildType at it instead of the debug keystore. Anchored on
  // the template's own comment so it cannot accidentally match the debug block.
  gradle = gradle.replace(
    /\/\/ Caution! In production, you need to generate your own keystore file\.\n(\s*)\/\/ see https:\/\/reactnative\.dev\/docs\/signed-apk-android\.\n\s*signingConfig signingConfigs\.debug/,
    `signingConfig signingConfigs.release`,
  );
  if (!gradle.includes('signingConfig signingConfigs.release')) {
    console.error('FAILED to repoint release signingConfig — template changed. Aborting.');
    process.exit(1);
  }
  console.log('build.gradle: release signingConfig wired to the upload keystore');
} else {
  console.log('build.gradle: release signingConfig already wired');
}

const before = gradle.match(/versionCode\s+(\d+)/)?.[1];
gradle = gradle.replace(/versionCode\s+\d+/, `versionCode ${versionCode}`);
console.log(`build.gradle: versionCode ${before} -> ${versionCode}`);

// --- 3. WINDOWS ONLY: resolve sentry.gradle ourselves ---
// The template locates @sentry/react-native by shelling out from Groovy:
//   apply from: new File(["node","--print","…require.resolve(…)"].execute()…, "sentry.gradle")
// `.execute()` does not go through a shell, so on Windows bare `node` does not
// resolve and `.text` comes back EMPTY — leaving `new File("", "sentry.gradle")`,
// i.e. a relative lookup that fails with "Could not read script
// android\app\sentry.gradle". It works on EAS because that builder is Linux.
// Node is already resolving modules here, so substitute the absolute path.
const sentryApply = /apply from: new File\(\["node".*?"sentry\.gradle"\)/s;
if (sentryApply.test(gradle)) {
  const sentryGradle = resolve(
    dirname(fileURLToPath(import.meta.resolve('@sentry/react-native/package.json'))),
    'sentry.gradle',
  );
  if (!existsSync(sentryGradle)) {
    console.error(`sentry.gradle not found at ${sentryGradle}`);
    process.exit(1);
  }
  gradle = gradle.replace(sentryApply, `apply from: "${sentryGradle.replace(/\\/g, '/')}"`);
  console.log('build.gradle: sentry.gradle resolved to an absolute path (Windows fix)');
}

writeFileSync(buildGradlePath, gradle);

// --- 4. AndroidManifest.xml: the EAS Update channel ---
// The whole reason a raw-Gradle build was forbidden. `expo prebuild` does not read
// `eas.json`, so nothing writes the channel; expo-updates then sends no
// `expo-channel-name` header and the binary can never receive an update. Nothing
// errors at build time or at runtime — it just never updates, which is what vc 10
// did. Key name is from `expo-updates/android/.../UpdatesConfiguration.kt:253`.
const manifestPath = resolve(mobileRoot, 'android/app/src/main/AndroidManifest.xml');
let manifest = readFileSync(manifestPath, 'utf8');

const HEADERS_KEY = 'expo.modules.updates.UPDATES_CONFIGURATION_REQUEST_HEADERS_KEY';
if (manifest.includes(HEADERS_KEY)) {
  console.log('AndroidManifest.xml: update request headers already present');
} else {
  // Anchored on EXPO_UPDATE_URL. If expo-updates is not configured at all, a
  // channel is meaningless — fail loudly rather than ship a binary that silently
  // cannot update, which is the exact failure this step exists to prevent.
  const anchor = /( *)<meta-data android:name="expo\.modules\.updates\.EXPO_UPDATE_URL".*?\/>/;
  if (!anchor.test(manifest)) {
    console.error(
      'EXPO_UPDATE_URL absent from AndroidManifest.xml — expo-updates is not configured.\n' +
        'Refusing to inject a channel into a build that could not update anyway.',
    );
    process.exit(1);
  }
  const value = JSON.stringify({ 'expo-channel-name': channel }).replace(/"/g, '&quot;');
  manifest = manifest.replace(
    anchor,
    (line, indent) => `${line}\n${indent}<meta-data android:name="${HEADERS_KEY}" android:value="${value}"/>`,
  );
  writeFileSync(manifestPath, manifest);
  console.log(`AndroidManifest.xml: EAS Update channel "${channel}" injected`);
}
